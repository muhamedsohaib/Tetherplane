import assert from "node:assert/strict";
import fs from "node:fs";
import {createHash} from "node:crypto";
import {execFileSync} from "node:child_process";
const [input,output]=process.argv.slice(2);
assert.ok(input && output,"report and evidence paths required");
const report=JSON.parse(fs.readFileSync(input,"utf8"));
assert.equal(report.execution,"staging_acceptance");
assert.equal(report.portal_test_topology,"disposable_combined_mutable");
assert.equal(report.acceptance_verified,false);
assert.equal(report.platform,"linux");
assert.equal(report.allowPartial,true);
assert.equal(report.outcome.ok,true);
assert.deepEqual(report.outcome.failed,[]);
const expected={G1:"PASS",G2:"PASS",G3:"PASS",G4:"BLOCKED",G5:"PASS",G6:"BLOCKED",G7:"PASS"};
const statuses=Object.fromEntries(Object.keys(expected).map(id=>[id,report.gates?.[id]?.status]));
assert.deepEqual(statuses,expected);
const mobile=Object.fromEntries(Array.from({length:10},(_,i)=>"M"+(i+1)).map(id=>[id,report.gates.G6.mobileChecks?.[id]?.status]));
assert.ok(Object.values(mobile).every(status=>status==="PASS"),"mobile emulation evidence incomplete");
const git=(...args)=>execFileSync("git",args,{encoding:"utf8"}).trim();
const sha=git("rev-parse","HEAD");
assert.match(sha,/^[a-f0-9]{40}$/);
assert.equal(sha,process.env.GITHUB_SHA);
assert.equal(git("status","--porcelain"),"","candidate tree not clean");
const hash=filename=>createHash("sha256").update(fs.readFileSync(filename)).digest("hex");
const evidence={schema:1,execution:"actual_isolated_ci_rehearsal",release_certified:false,portal_test_topology:report.portal_test_topology,source_commit:sha,source_tree:git("rev-parse","HEAD^{tree}"),run_id:process.env.GITHUB_RUN_ID,run_attempt:process.env.GITHUB_RUN_ATTEMPT,platform:process.platform,run_at:report.runAt,agent_sha256:hash("target/debug/tetherd"),relay_sha256:hash("relay/dist/cli.js"),extension_sha256:hash("extension/browser/dist/background.js"),gates:statuses,mobile_emulation:mobile};
fs.writeFileSync(output,JSON.stringify(evidence,null,2)+"\n");
console.log(JSON.stringify(evidence,null,2));
